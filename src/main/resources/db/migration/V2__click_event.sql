-- V2 (brownfield): per-click analytics. Privacy by design: no IP address, no full referrer
-- URL, no raw user agent is stored; only coarse, non-identifying attributes.
CREATE TABLE click_event (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    link_id        BIGINT       NOT NULL,
    clicked_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    clicked_on     DATE         NOT NULL,     -- UTC day, denormalised for cheap GROUP BY
    referrer_host  VARCHAR(255),
    agent_family   VARCHAR(32)  NOT NULL,
    CONSTRAINT fk_click_event_link FOREIGN KEY (link_id) REFERENCES short_link (id) ON DELETE CASCADE
);

CREATE INDEX ix_click_event_link_day ON click_event (link_id, clicked_on);
